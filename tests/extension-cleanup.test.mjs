import assert from 'node:assert/strict';
import { cleanExtensionData, LOCAL_CACHE_KEYS } from '../src/extension-cleanup.js';
const entries = new Map(LOCAL_CACHE_KEYS.map(key => [key, 'old']));
entries.set('scenepulse_panel_library_v1', 'library');
entries.set('unrelated', 'keep');
const local = { removeItem: key => entries.delete(key) };
const sessionEntries = new Map([['sp:preset-shown', 'old'], ['other', 'keep']]);
const session = { removeItem: key => sessionEntries.delete(key) };
const ctx = { extensionSettings: { scenepulse: { enabled: false, profiles: ['old'] }, other: { keep: true } }, chatMetadata: { scenepulse: { snapshots: ['precious'] } } };
const before = structuredClone(ctx.chatMetadata);
let cleared = 0;
await cleanExtensionData({ context: ctx, local, session, clearDiagnostics: async () => { cleared++; } });
assert.equal(ctx.extensionSettings.scenepulse, undefined);
assert.deepEqual(ctx.extensionSettings.other, { keep: true });
assert.deepEqual(ctx.chatMetadata, before);
assert.deepEqual([...entries], [['scenepulse_panel_library_v1', 'library'], ['unrelated', 'keep']]);
assert.deepEqual([...sessionEntries], [['other', 'keep']]);
assert.equal(cleared, 1);
await cleanExtensionData({ context: ctx, local, session, clearDiagnostics: async () => {} });
assert.deepEqual(ctx.chatMetadata, before, 'cleanup is idempotent');
await assert.rejects(cleanExtensionData({ context: ctx, local, session, clearDiagnostics: async () => { throw new Error('offline'); } }), /offline/);
console.log('extension-cleanup: passed');
